function generateSecret(length = 48) {
  return crypto.randomBytes(length).toString('base64url').slice(0, length);
}

function generatePassword(length = 24) {
  return crypto.randomBytes(length).toString('base64url').slice(0, length);
}

function prompt(question, defaultValue) {
  // Synchronous prompt using readline
  const readline = require('readline');
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const promptText = defaultValue ? `${question} [${defaultValue}]: ` : `${question}: `;
    rl.question(promptText, (answer) => {
      rl.close();
      const trimmed = answer.trim();
      resolve(trimmed || defaultValue || '');
    });
  });
}

// ── Discovery functions ─────────────────────────────────────────────

/**
 * Discover PostgreSQL configuration from multiple sources.
 * Priority: existing .env DATABASE_URL > docker compose > shared env > local probe.
 */
async function discoverPostgreSQL(existingEnv) {
  const result = await createPostgresDetector().discover({ datasource: existingEnv.DATABASE_URL });
  return { host: result.connection?.host || null, port: result.connection?.port || null, database: result.connection?.database || null, source: result.source, status: result.status };
}

/**
 * Discover 3X-UI panel configuration from installer-state, .env, and Docker.
 */
async function discoverXUI(existingEnv, state) {
  const result = await createXuiDetector().discover({ baseUrl: existingEnv.XUI_PANEL_BASE_URL });
  return { baseUrl: result.connection?.url || null, subPort: result.connection?.port || null, subPath: result.connection?.webBasePath || null, source: result.source, status: result.status };
}

/**
 * Discover Telegram bot configuration.
 */
function discoverTelegram(existingEnv) {
  return {
    botToken: existingEnv.TELEGRAM_BOT_TOKEN || null,
    adminIds: existingEnv.TELEGRAM_ADMIN_IDS || null,
  };
}

// ── Main auto-config runner ─────────────────────────────────────────

/**
 * Run the full auto-configuration flow.
 * @param {object} opts - { nonInteractive: bool, env: object (override) }
 * @returns {Promise<{config: object, changed: string[], prompts: object}>}
 */
async function runAutoConfig(opts = {}) {
  const nonInteractive = !!opts.nonInteractive;
  const state = loadState(STATE_PATH);
  const existingEnv = opts.env || loadEnvFile(ENV_PATH);
  const exampleEnv = loadEnvFile(ENV_EXAMPLE_PATH);
  const changed = [];
  const prompts = {};

  // Start with existing .env values, fall back to .env.example defaults
  const config = {};
  for (const [k, v] of Object.entries(exampleEnv)) {
    config[k] = existingEnv[k] !== undefined ? existingEnv[k] : v;
  }
  // Also include any keys in existing .env not in example
  for (const [k, v] of Object.entries(existingEnv)) {
    if (config[k] === undefined) config[k] = v;
  }

  // ── PostgreSQL ──
  console.log('\n[1/5] Discovering PostgreSQL...');
  const pg = await discoverPostgreSQL(config);
  if (pg.host) {
    console.log(`  ✓ Found PostgreSQL via ${pg.source}: ${pg.host}:${pg.port}/${pg.database}`);
    config.POSTGRES_HOST = pg.host;
    config.POSTGRES_PORT = pg.port;
    config.VPN_DATABASE = pg.database;
    changed.push('postgresql');
    setEntry(state, 'db.discovered', pg, { source: pg.source, confidence: 'high', ttlSeconds: 3600 });
  } else {
    console.log('  ✗ PostgreSQL not found — will use defaults');
    if (!config.DATABASE_URL) {
      config.DATABASE_URL = `postgresql://${config.POSTGRES_USER}:${config.POSTGRES_PASSWORD}@${config.POSTGRES_HOST}:${config.POSTGRES_PORT}/${config.VPN_DATABASE}?schema=public`;
    }
  }

  // ── 3X-UI ──
  console.log('\n[2/5] Discovering 3X-UI panel...');
  const xui = await discoverXUI(config, state);
  if (xui.baseUrl) {
    console.log(`  ✓ Found 3X-UI via ${xui.source}: ${xui.baseUrl}`);
    config.XUI_PANEL_BASE_URL = xui.baseUrl;
    config.XUI_PANEL_SUB_PORT = xui.subPort;
    config.XUI_PANEL_SUB_PATH = xui.subPath;
    changed.push('xui');
    setEntry(state, 'xui.autoConfig', xui, { source: xui.source, confidence: 'high', ttlSeconds: 3600 });
  } else {
    console.log('  ✗ 3X-UI panel not found — will need manual configuration');
  }

  // ── Generate secrets (JWT, S3, encryption, webhook) ──
  console.log('\n[3/5] Generating missing secrets...');
  const secretsToGenerate = [
    { key: 'JWT_ACCESS_SECRET', length: 48 },
    { key: 'JWT_REFRESH_SECRET', length: 48 },
    { key: 'ENCRYPTION_KEY', length: 32 },
    { key: 'WEBHOOK_SECRET', length: 32 },
  ];
  for (const { key, length } of secretsToGenerate) {
    const current = config[key] || '';
    const isDefault = !current || current.includes('change-me') || current.length < 16;
    if (isDefault) {
      config[key] = generateSecret(length);
      console.log(`  ✓ Generated ${key}`);
      changed.push(key);
    } else {
      console.log(`  ✓ ${key} already set (keeping existing)`);
    }
  }

  // S3 keys — generate if still default
  if (!config.S3_ACCESS_KEY || config.S3_ACCESS_KEY === 'minioadmin') {
    config.S3_ACCESS_KEY = 'tazaxy-' + generateSecret(12);
    console.log('  ✓ Generated S3_ACCESS_KEY');
    changed.push('S3_ACCESS_KEY');
  }
  if (!config.S3_SECRET_KEY || config.S3_SECRET_KEY === 'minioadmin') {
    config.S3_SECRET_KEY = generateSecret(32);
    console.log('  ✓ Generated S3_SECRET_KEY');
    changed.push('S3_SECRET_KEY');
  }

  // ── Telegram (only prompt if missing) ──
  console.log('\n[4/5] Checking Telegram configuration...');
  const tg = discoverTelegram(config);
  if (!tg.botToken || tg.botToken === '123456:ABC-DEF') {
    if (nonInteractive) {
      console.log('  ⊘ TELEGRAM_BOT_TOKEN not set (skipped in non-interactive mode)');
      prompts.TELEGRAM_BOT_TOKEN = null;
    } else {
      console.log('  ? TELEGRAM_BOT_TOKEN not found — prompting user');
      const token = await prompt('Enter your Telegram Bot Token (from @BotFather), or press Enter to skip:');
      if (token) {
        config.TELEGRAM_BOT_TOKEN = token;
        changed.push('TELEGRAM_BOT_TOKEN');
        console.log('  ✓ Telegram bot token saved');
      } else {
        console.log('  ⊘ Skipped — bot will not start until token is set');
      }
      prompts.TELEGRAM_BOT_TOKEN = token || null;
    }
  } else {
    console.log(`  ✓ TELEGRAM_BOT_TOKEN already set`);
  }

  if (!tg.adminIds || tg.adminIds === '123456789,987654321') {
    if (nonInteractive) {
      console.log('  ⊘ TELEGRAM_ADMIN_IDS not set (skipped in non-interactive mode)');
      prompts.TELEGRAM_ADMIN_IDS = null;
    } else {
      console.log('  ? TELEGRAM_ADMIN_IDS not found — prompting user');
      const adminIds = await prompt('Enter your Telegram Admin ID(s) (comma-separated, from @userinfobot), or press Enter to skip:');
      if (adminIds) {
        config.TELEGRAM_ADMIN_IDS = adminIds;
        changed.push('TELEGRAM_ADMIN_IDS');
        console.log('  ✓ Telegram admin IDs saved');
      }
      prompts.TELEGRAM_ADMIN_IDS = adminIds || null;
    }
  } else {
    console.log('  ✓ TELEGRAM_ADMIN_IDS already set');
  }

  // ── Write .env ──
  console.log('\n[5/5] Writing configuration to .env...');
  writeEnvFile(ENV_PATH, config);
  console.log(`  ✓ Configuration written to ${ENV_PATH}`);
  console.log(`  ✓ ${changed.length} value(s) updated`);

  // Save state
  setEntry(state, 'config.written', { envPath: ENV_PATH, changedKeys: changed }, { source: 'auto-config', confidence: 'high', ttlSeconds: 1800 });
  saveState(STATE_PATH, state);

  return { config, changed, prompts };
}

module.exports = { runAutoConfig, discoverPostgreSQL, discoverXUI, discoverTelegram, writeEnvFile, loadEnvFile, generateSecret, generatePassword };

// Run directly if invoked as a script
if (require.main === module) {
  runAutoConfig({ nonInteractive: process.argv.includes('--non-interactive') })
    .then(({ changed }) => {
      console.log('\n=== Auto-configuration complete ===');
      console.log(`Updated: ${changed.join(', ') || 'nothing'}`);
      process.exit(0);
    })
    .catch((e) => {
      console.error('Auto-config failed:', e.message || e);
      process.exit(1);
    });
}
