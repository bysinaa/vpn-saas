#!/usr/bin/env node
/**
 * auto-config.js
 *
 * Smart auto-configuration engine for the TAZAXY installer.
 * Performs discovery-first configuration: detects everything it can from
 * the environment, Docker, existing config files, and installer-state cache
 * BEFORE asking the user any questions. Only genuinely undiscoverable values
 * (e.g. Telegram bot token) prompt the user.
 *
 * Design principles:
 *  - Never ask before discovery is complete.
 *  - Cache results in installer-state.json with timestamps + validation.
 *  - Generate secrets (JWT, S3 keys, encryption key) automatically.
 *  - Recover existing credentials from .env, docker-compose, shared env.
 *  - One canonical .env written by the installer, read by everyone.
 *
 * Exports:
 *  - runAutoConfig(opts) → Promise<{ config, changed, prompts }>
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { exec } = require('child_process');
const { loadState, saveState, setEntry, getValidatedEntry } = require('./state-manager');
const { createPostgresDetector } = require('./postgres-detector');
const { createXuiDetector } = require('./xui-detector');

const STATE_PATH = path.resolve(process.cwd(), 'installer-state.json');
const ENV_PATH = path.resolve(process.cwd(), '.env');
const ENV_EXAMPLE_PATH = path.resolve(process.cwd(), '.env.example');

// ── Helpers ────────────────────────────────────────────────────────

function runCmd(cmd, opts = {}) {
  const timeout = opts.timeout || 10000;
  return new Promise((resolve) => {
    exec(cmd, { timeout, shell: true }, (err, stdout, stderr) => {
      resolve({
        success: !err,
        code: err && err.code != null ? err.code : 0,
        stdout: stdout ? stdout.trim() : '',
        stderr: stderr ? stderr.trim() : '',
      });
    });
  });
}

function parseEnvFile(content) {
  const out = {};
  if (!content) return out;
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx < 0) continue;
    const key = trimmed.substring(0, eqIdx).trim();
    let value = trimmed.substring(eqIdx + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function loadEnvFile(filePath) {
  try {
    if (fs.existsSync(filePath)) return parseEnvFile(fs.readFileSync(filePath, 'utf8'));
  } catch (_) { /* non-fatal */ }
  return {};
}

